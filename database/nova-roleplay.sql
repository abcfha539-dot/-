CREATE TABLE IF NOT EXISTS admins (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  username VARCHAR(60) NOT NULL UNIQUE,
  password_hash VARCHAR(255) NOT NULL,
  display_name VARCHAR(100) NOT NULL,
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS application_settings (
  slug VARCHAR(80) PRIMARY KEY,
  is_open TINYINT(1) NOT NULL DEFAULT 0,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS applications (
  id BIGINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  public_id VARCHAR(40) NOT NULL UNIQUE,
  type_slug VARCHAR(80) NOT NULL,
  type_title VARCHAR(150) NOT NULL,
  player_name VARCHAR(80) NOT NULL,
  discord_name VARCHAR(80) NOT NULL,
  discord_id VARCHAR(30) NULL,
  age TINYINT UNSIGNED NOT NULL,
  experience TEXT NOT NULL,
  reason TEXT NOT NULL,
  status ENUM('pending','accepted','rejected') NOT NULL DEFAULT 'pending',
  created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
  INDEX idx_app_status (status), INDEX idx_app_created (created_at)
) ENGINE=InnoDB;

CREATE TABLE IF NOT EXISTS discord_users (
  discord_id VARCHAR(30) PRIMARY KEY,
  username VARCHAR(100) NOT NULL,
  global_name VARCHAR(100) NOT NULL DEFAULT '',
  avatar_hash VARCHAR(150) NOT NULL DEFAULT '',
  email VARCHAR(190) NOT NULL DEFAULT '',
  first_login_at DATETIME NOT NULL,
  last_login_at DATETIME NOT NULL,
  login_count INT UNSIGNED NOT NULL DEFAULT 1
) ENGINE=InnoDB;
